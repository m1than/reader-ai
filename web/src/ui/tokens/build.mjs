#!/usr/bin/env node
// Compiles the Calm tokens (calm.tokens.json, W3C Design Tokens) into calm.css (WEB-UI FR-UI-2).
//   node web/src/ui/tokens/build.mjs      writes calm.css next to this file
// The CSS is unlayered, so it wins over the library's @layer acme.tokens. Calm removes gradients, glass and glow by
// mapping those tokens to flat values, and sets every duration to 0 under prefers-reduced-motion. Deterministic: the
// same tokens give byte-identical output.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const vars = (set) =>
  Object.entries(set)
    .map(([name, { $value }]) => `  --acme-${name}: ${$value};`)
    .join('\n');

const flat = (set) =>
  [
    `  --acme-holo: ${set.accent.$value};`,
    `  --acme-holo-soft: color-mix(in srgb, ${set.accent.$value} 12%, transparent);`,
    `  --acme-glass: ${set.surface.$value};`,
    '  --acme-glass-blur: 0px;',
    '  --acme-glow: none;',
    `  --acme-hover: color-mix(in srgb, ${set.text.$value} 5%, transparent);`,
    `  --acme-pressed: color-mix(in srgb, ${set.text.$value} 9%, transparent);`,
    `  --acme-backdrop: color-mix(in srgb, ${set.canvas.$value} 60%, transparent);`,
    '  --acme-shadow: 0 1px 2px rgb(0 0 0 / 0.08), 0 4px 12px rgb(0 0 0 / 0.08);',
  ].join('\n');

const indent = (text) =>
  text
    .split('\n')
    .map((line) => `  ${line}`)
    .join('\n');

/** @param {Record<string, Record<string, { $value: string }>>} tokens */
export const buildCss = (tokens) =>
  [
    '/* Generated by build.mjs from calm.tokens.json (WEB-UI FR-UI-2). Do not edit. */',
    `:root {\n  color-scheme: dark;\n${vars(tokens.dark)}\n${flat(tokens.dark)}\n}`,
    `:root[data-theme='light'] {\n  color-scheme: light;\n${vars(tokens.light)}\n${flat(tokens.light)}\n}`,
    `@media (prefers-color-scheme: light) {\n  :root:not([data-theme='dark']) {\n    color-scheme: light;\n${indent(vars(tokens.light))}\n${indent(flat(tokens.light))}\n  }\n}`,
    '@media (prefers-reduced-motion: reduce) {\n  :root {\n    --acme-duration: 0ms;\n    --acme-duration-slow: 0ms;\n  }\n}',
    'html {\n  background: var(--acme-canvas);\n  color: var(--acme-text);\n}',
    '',
  ].join('\n\n');

const here = dirname(fileURLToPath(import.meta.url));
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const tokens = JSON.parse(readFileSync(join(here, 'calm.tokens.json'), 'utf8'));
  writeFileSync(join(here, 'calm.css'), buildCss(tokens));
}
