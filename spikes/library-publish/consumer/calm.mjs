#!/usr/bin/env node
// Calm draft: checks WCAG 2.2 contrast of calm.tokens.json and generates calm.css from it.
//   node calm.mjs            prints every pair, writes calm.css and ../results/contrast.json, exit 1 on any FAIL
// Text pairs need 4.5:1 (SC 1.4.3); control borders, focus and accent fills need 3:1 against what they sit on (SC 1.4.11).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const tokens = JSON.parse(readFileSync(join(here, 'calm.tokens.json'), 'utf8'));

const channel = (c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const luminance = (hex) => {
  const [r, g, b] = [1, 3, 5].map((i) => channel(parseInt(hex.slice(i, i + 2), 16) / 255));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const ratio = (a, b) => {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
};

const SURFACES = ['canvas', 'surface', 'surface-raised'];
const TEXT = ['text', 'text-muted', 'accent', 'success', 'warning', 'danger', 'info'];
const NON_TEXT = ['control-border', 'focus', 'accent'];
const pairs = [
  ...TEXT.flatMap((fg) => SURFACES.map((bg) => ({ fg, bg, kind: 'text', min: 4.5 }))),
  { fg: 'on-tone', bg: 'accent', kind: 'text', min: 4.5 },
  ...NON_TEXT.flatMap((fg) => SURFACES.map((bg) => ({ fg, bg, kind: 'non-text', min: 3 }))),
];

const results = Object.entries(tokens)
  .filter(([mode]) => !mode.startsWith('$'))
  .flatMap(([mode, set]) => pairs.map(({ fg, bg, kind, min }) => {
    const value = ratio(set[fg].$value, set[bg].$value);
    return { mode, fg, bg, kind, min, ratio: Math.round(value * 100) / 100, pass: value >= min };
  }));

results.forEach(({ mode, fg, bg, ratio: r, min, pass }) =>
  console.log(`${pass ? 'PASS' : 'FAIL'} ${mode.padEnd(5)} ${fg.padEnd(14)} on ${bg.padEnd(14)} ${r.toFixed(2)}:1 (min ${min})`));

// Generated CSS: unlayered, so it wins over the library's @layer acme.tokens. Calm removes gradients,
// glass and glow by mapping those tokens to flat values.
const vars = (set) => Object.entries(set).map(([name, { $value }]) => `  --acme-${name}: ${$value};`).join('\n');
const flat = (set) => [
  `  --acme-holo: ${set.accent.$value};`,
  `  --acme-holo-soft: color-mix(in srgb, ${set.accent.$value} 12%, transparent);`,
  `  --acme-glass: ${set.surface.$value};`,
  '  --acme-glass-blur: 0px;',
  '  --acme-glow: none;',
  `  --acme-hover: color-mix(in srgb, ${set.text.$value} 5%, transparent);`,
  `  --acme-pressed: color-mix(in srgb, ${set.text.$value} 9%, transparent);`,
  `  --acme-backdrop: color-mix(in srgb, ${set.canvas.$value} 60%, transparent);`,
  '  --acme-shadow: 0 1px 2px rgb(0 0 0 / 0.08), 0 8px 24px rgb(0 0 0 / 0.08);',
].join('\n');
const css = [
  '/* Generated by calm.mjs from calm.tokens.json. Do not edit. */',
  `:root {\n  color-scheme: dark;\n${vars(tokens.dark)}\n${flat(tokens.dark)}\n}`,
  `:root[data-theme='light'] {\n  color-scheme: light;\n${vars(tokens.light)}\n${flat(tokens.light)}\n}`,
  `@media (prefers-color-scheme: light) {\n  :root:not([data-theme='dark']) {\n    color-scheme: light;\n${vars(tokens.light).replaceAll('\n', '\n  ').replace(/^/, '  ')}\n${flat(tokens.light).replaceAll('\n', '\n  ').replace(/^/, '  ')}\n  }\n}`,
  '@media (prefers-reduced-motion: reduce) {\n  :root { --acme-duration: 0ms; --acme-duration-slow: 0ms; }\n}',
  '',
].join('\n\n');
writeFileSync(join(here, 'calm.css'), css);
mkdirSync(join(here, '..', 'results'), { recursive: true });
writeFileSync(join(here, '..', 'results', 'contrast.json'), `${JSON.stringify(results, null, 2)}\n`);

const failed = results.filter(({ pass }) => !pass);
console.log(`\n${results.length - failed.length} of ${results.length} pairs pass`);
process.exit(failed.length ? 1 : 0);
