"""Build pilot/bashir/course.yaml from plan.yaml and the PDF bookmark outline.

Usage: uv run pilot/bashir/build_course.py <path-to-bashir.pdf>

The PDF is the owner's personal copy and is never committed; its sha256 must match plan.yaml.
Lessons are chapters; stages group them in plan order. Sections and subsections come from
the bookmark outline (ADR-0008: outline first).
"""

import hashlib
import re
import sys
from pathlib import Path

import yaml
from pypdf import PdfReader

HERE = Path(__file__).parent
CHAPTER = re.compile(r"^Глава (\d+)\. (.+)$")


def clean(title: str) -> str:
    return re.sub(r"\s+", " ", title.replace("\xa0", " ")).strip()


def outline(reader: PdfReader) -> list[dict]:
    def walk(items, level):
        for item in items:
            if isinstance(item, list):
                yield from walk(item, level + 1)
            else:
                yield {
                    "level": level,
                    "title": clean(item.title),
                    "pdf_page": reader.get_destination_page_number(item) + 1,
                }

    return list(walk(reader.outline, 0))


def chapters(entries: list[dict], total_pages: int) -> dict[int, dict]:
    tops = [i for i, e in enumerate(entries) if e["level"] == 0]
    bounds = zip(tops, tops[1:] + [len(entries)])
    found = {}
    for start, end in bounds:
        match = CHAPTER.match(entries[start]["title"])
        if not match:
            continue
        last_pdf = entries[end]["pdf_page"] - 1 if end < len(entries) else total_pages
        found[int(match[1])] = {
            "title": match[2],
            "pdf": [entries[start]["pdf_page"], last_pdf],
            "children": entries[start + 1 : end],
        }
    return found


def sections(children: list[dict], offset: int) -> list[dict]:
    heads = [i for i, e in enumerate(children) if e["level"] == 1]
    return [
        {
            "title": children[i]["title"],
            "book_page": children[i]["pdf_page"] - offset,
            **(
                {"subsections": [e["title"] for e in children[i + 1 : j]]}
                if j > i + 1
                else {}
            ),
        }
        for i, j in zip(heads, heads[1:] + [len(children)])
    ]


def budget(stage: dict) -> int | None:
    theory = stage.get("theory_h")
    return None if theory is None else round((theory + stage["code_h"]) * 1.2)


def build(pdf: Path) -> dict:
    plan = yaml.safe_load((HERE / "plan.yaml").read_text(encoding="utf-8"))
    material = plan["material"]
    digest = hashlib.sha256(pdf.read_bytes()).hexdigest()
    if digest != material["sha256"]:
        sys.exit(f"sha256 mismatch: {digest} != {material['sha256']}")

    reader = PdfReader(pdf)
    entries = outline(reader)
    by_number = chapters(entries, len(reader.pages))
    offset = material["page_offset"]
    order = iter(range(1, len(by_number) + 1))

    stages = [
        {
            "id": stage["id"],
            "title": stage["title"],
            "budget_sessions": budget(stage),
            **({"wallet_output": stage["wallet_output"]} if "wallet_output" in stage else {}),
            "lessons": [
                {
                    "id": f"L{n:02d}",
                    "plan_order": next(order),
                    "chapter": n,
                    "title": by_number[n]["title"],
                    "pages": {
                        "book": [p - offset for p in by_number[n]["pdf"]],
                        "pdf": by_number[n]["pdf"],
                    },
                    "status": "drafted" if n in plan["drafted"] else "outlined",
                    "sections": sections(by_number[n]["children"], offset),
                }
                for n in stage["chapters"]
            ],
        }
        for stage in plan["stages"]
    ]

    planned = sorted(n for s in plan["stages"] for n in s["chapters"])
    if planned != sorted(by_number):
        sys.exit(f"plan covers chapters {planned}, the PDF has {sorted(by_number)}")

    return {
        "course": "bashir-mastering-blockchain-ru-2025",
        "material": material,
        "outline": {"bookmarks": len(entries), "chapters": len(by_number)},
        "budget_sessions_total": sum(s["budget_sessions"] or 0 for s in stages),
        "stages": stages,
    }


if __name__ == "__main__":
    course = build(Path(sys.argv[1]))
    header = (
        "# GENERATED by pilot/bashir/build_course.py from plan.yaml and the PDF bookmark outline.\n"
        "# Do not edit by hand: change plan.yaml and rerun.\n"
    )
    body = yaml.safe_dump(course, allow_unicode=True, sort_keys=False, width=120)
    (HERE / "course.yaml").write_text(header + body, encoding="utf-8")
    print(f"course.yaml: {sum(len(s['lessons']) for s in course['stages'])} lessons")
